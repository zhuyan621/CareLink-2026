def get_translator() -> "Callable[[str], str]":
    """Return a bound translation function for the current session language."""
    lang = st.session_state.get("lang", "zh")
    i18n_dict = I18N.get(lang, I18N["zh"])

    def t(key: str, **kwargs) -> str:
        text = i18n_dict.get(key, key)
        if kwargs:
            return text.format(**kwargs)
        return text

    return t


# Module-level convenience (reads current session state on each call)
def t(key: str, **kwargs) -> str:
    """Convenience function — calls get_translator internally."""
    return get_translator()(key, **kwargs)
